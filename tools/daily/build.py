# -*- coding: utf-8 -*-
"""Write src/data/daily.js and the Supabase sync SQL from the verse files and the
calendar.

  python build.py                    daily.js + out/sync.sql for every date from today on
  python build.py --from 2027-02-09  sync.sql only for dates on or after this one
  python build.py --to 2027-02-09    ...and on or before this one

daily.js exports three things:
  dailyEntries   the 50 core verses in their original order: the fallback rotation
                 the app uses for any day the calendar does not cover
  dailyVerses    every verse on the calendar, keyed by slug
  dailyCalendar  {"YYYY-MM-DD": slug}

The sync SQL upserts each scheduled verse into comms.daily_pool (keyed by slug)
and each date into comms.daily_schedule. Today and earlier are never rewritten in
the schedule: those rows use "on conflict do nothing", so a date that has already
been emailed keeps the verse it went out with.
"""
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import lib
from render import writeup_html


def entry(v):
    return {"slug": v["slug"], "ref": v["ref"], "verse": v["verse"], "story": v["story"], "studyUrl": v["studyUrl"]}


def js_obj(e, indent="  "):
    return (f"{indent}{{\n"
            f"{indent}  slug: {json.dumps(e['slug'])},\n"
            f"{indent}  ref: {json.dumps(e['ref'])},\n"
            f"{indent}  verse: {json.dumps(e['verse'])},\n"
            f"{indent}  story: {json.dumps(e['story'], ensure_ascii=False)},\n"
            f"{indent}  studyUrl: {json.dumps(e['studyUrl'])}\n"
            f"{indent}}}")


def write_daily_js(verses, cal):
    core = sorted((v for v in verses.values() if v.get("core")), key=lambda v: v["core"])
    scheduled = sorted({s for s in cal.values()})
    out = [
        "// GENERATED by tools/daily/build.py. Do not edit by hand: edit the files in",
        "// tools/daily/verses/ and tools/daily/calendar.json, then rerun build.py.",
        "//",
        "// The app shows dailyCalendar[today] when the calendar covers today, and falls",
        "// back to the core rotation (dailyEntries, by day of the year) when it does not,",
        "// so a frozen app bundle never runs out of verses. Verse text is verbatim BSB",
        "// from the study JSON.",
        "",
        "export const dailyEntries = [",
        ",\n".join(js_obj(entry(v)) for v in core),
        "];",
        "",
        "export const dailyVerses = {",
        ",\n".join(f"  {json.dumps(s)}: {js_obj(entry(verses[s]), '  ').lstrip()}" for s in scheduled),
        "};",
        "",
        "export const dailyCalendar = " + json.dumps(dict(sorted(cal.items())), indent=2) + ";",
        "",
    ]
    js = "\n".join(out)
    if any(c in js for c in lib.DASHES):
        raise SystemExit("daily.js would contain an em or en dash; run check.py")
    with open(lib.DAILY_JS, "w", encoding="utf-8") as f:
        f.write(js)
    return len(core), len(scheduled)


FEED = os.path.join(lib.PUBLIC, "feed.json")
FEED_DAYS = 400   # the feed carries the last FEED_DAYS days of the calendar


def feed_text(verses, cal):
    """public/daily/feed.json: the calendar and the email fields for each verse.
    comms.daily_sync_apply() in Supabase fetches it from makor.co.za every
    morning, so the email calendar follows the deployed site on its own.
    Deterministic for a given calendar (no dependence on today's date)."""
    import datetime as dt
    if not cal:
        dates = []
    else:
        last = lib.parse_date(max(cal))
        cut = lib.iso(last - dt.timedelta(days=FEED_DAYS))
        dates = [d for d in sorted(cal) if d >= cut]
    slugs = sorted({cal[d] for d in dates})
    feed = {
        "version": 1,
        "calendar": {d: cal[d] for d in dates},
        "verses": {s: {
            "ref": verses[s]["ref"],
            "verse_text": verses[s]["verse"],
            "writeup_html": writeup_html(verses[s]["story"]),
            "writeup_txt": "\n\n".join(verses[s]["story"]),
            "study_url": lib.SITE + verses[s]["studyUrl"],
            "daily_page_url": f"{lib.SITE}/daily/{s}/",
            "image_path": f"/daily/{s}.png",
            "og_image_path": f"/daily/{s}-share.png",
        } for s in slugs},
    }
    return json.dumps(feed, ensure_ascii=False, indent=1) + "\n", len(dates)


def write_feed(verses, cal):
    text, n = feed_text(verses, cal)
    with open(FEED, "w", encoding="utf-8") as f:
        f.write(text)
    return n


def sq(s):
    """SQL string literal. Text with line breaks becomes an E'' literal with \\n
    escapes, so every statement in sync.sql stays on one line and can be split
    into chunks line by line."""
    s = str(s)
    if "\n" in s or "\\" in s:
        return "E'" + s.replace("\\", "\\\\").replace("'", "''").replace("\n", "\\n") + "'"
    return "'" + s.replace("'", "''") + "'"


def write_sync_sql(verses, cal, start, end):
    today = lib.today()
    dates = [d for d in sorted(cal) if start <= d <= end]
    slugs = sorted({cal[d] for d in dates})
    lines = [f"-- Makor daily calendar sync, {len(dates)} dates ({dates[0] if dates else '-'} to {dates[-1] if dates else '-'}). Generated by tools/daily/build.py.",
             "begin;"]
    for s in slugs:
        v = verses[s]
        lines.append(
            "insert into comms.daily_pool (slug, ref, verse_text, writeup_html, writeup_txt, study_url, daily_page_url, image_path, og_image_path, active) values ("
            f"{sq(s)}, {sq(v['ref'])}, {sq(v['verse'])}, {sq(writeup_html(v['story']))}, {sq(chr(10).join(v['story']).replace(chr(10), chr(10) * 2))}, "
            f"{sq(lib.SITE + v['studyUrl'])}, {sq(lib.SITE + '/daily/' + s + '/')}, {sq('/daily/' + s + '.png')}, {sq('/daily/' + s + '-share.png')}, true) "
            "on conflict (slug) do update set ref = excluded.ref, verse_text = excluded.verse_text, writeup_html = excluded.writeup_html, "
            "writeup_txt = excluded.writeup_txt, study_url = excluded.study_url, daily_page_url = excluded.daily_page_url, "
            "image_path = excluded.image_path, og_image_path = excluded.og_image_path;")
    for d in dates:
        locked = d <= lib.iso(today)
        conflict = "do nothing" if locked else "do update set slug = excluded.slug, updated_at = now()"
        lines.append(f"insert into comms.daily_schedule (on_date, slug) values ({sq(d)}, {sq(cal[d])}) on conflict (on_date) {conflict};")
    lines.append("commit;")
    os.makedirs(lib.OUT_DIR, exist_ok=True)
    path = os.path.join(lib.OUT_DIR, "sync.sql")
    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    return path, len(dates), len(slugs)


def main(argv):
    start = lib.iso(lib.today())
    end = "9999-12-31"
    if "--from" in argv:
        start = argv[argv.index("--from") + 1]
    if "--to" in argv:
        end = argv[argv.index("--to") + 1]
    verses = lib.load_all_verses()
    cal = lib.load_calendar()
    missing = [s for s in cal.values() if s not in verses or not verses[s].get("story")]
    if missing:
        raise SystemExit(f"calendar names verses with no write-up yet: {sorted(set(missing))}")
    ncore, nsched = write_daily_js(verses, cal)
    nfeed = write_feed(verses, cal)
    path, nd, ns = write_sync_sql(verses, cal, start, end)
    print(f"daily.js: {ncore} core, {nsched} scheduled verses, {len(cal)} calendar days")
    print(f"feed.json: {nfeed} dates -> public/daily/feed.json (the email database pulls this)")
    print(f"sync.sql: {nd} dates, {ns} pool rows -> {os.path.relpath(path, lib.REPO)}")


if __name__ == "__main__":
    main(sys.argv[1:])
